// Validate generated CRS defs against the app's bundled proj4.js and emit
// crs-us.js. Usage: node tools/validate_crs_us.js raw.json > crs-us.js
const fs = require("fs");
const path = require("path");
const proj4 = require(path.join(__dirname, "..", "vendor", "proj4.js"));
const raw = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const defs = {}, bad = [];
for (const [k, d] of Object.entries(raw.defs)) {
  try {
    proj4.defs(k, d);
    // Round-trip the centre of the CRS's area of use: forward then inverse
    // must be finite and return within 1 cm-equivalent (1e-6 deg).
    const c = (raw.centres && raw.centres[k]) || [-95, 40];
    const xy = proj4("WGS84", k, c);
    const ll = proj4(k, "WGS84", xy);
    if (![...xy, ...ll].every(Number.isFinite)) throw new Error("non-finite");
    if (Math.abs(ll[0] - c[0]) > 1e-6 || Math.abs(ll[1] - c[1]) > 1e-6) throw new Error("round-trip mismatch");
    defs[k] = d;
  } catch (e) { bad.push(`${k} ${e.message}`); }
}
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "");
const names = {};
for (const [n, k] of Object.entries(raw.names)) if (defs[k]) names[norm(n)] = k;
process.stderr.write(`${Object.keys(defs).length} ok, ${bad.length} dropped\n${bad.slice(0, 30).join("\n")}\n`);
process.stdout.write(
  "// AUTO-GENERATED by tools/gen_crs_us.py + tools/validate_crs_us.js. Do not edit.\n" +
  "// proj4 definitions for every US-area projected CRS (EPSG + ESRI, incl. county systems),\n" +
  "// bundled so georeferenced IFCs work offline. Loaded before ifc-viewer.js.\n" +
  "window.CRS_US_DEFS=" + JSON.stringify(defs) + ";\n" +
  "window.CRS_US_NAMES=" + JSON.stringify(names) + ";\n");
