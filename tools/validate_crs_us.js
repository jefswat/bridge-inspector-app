// Validate generated CRS defs against the app's bundled proj4.js and write
//   crs-us.js        core (state-level) systems, shipped + precached
//   crs-us-extra.js  county / city / regional / world systems, fetched on demand
// Usage: node tools/validate_crs_us.js raw.json
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const proj4 = require(path.join(root, "vendor", "proj4.js"));
const raw = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const out = { core: { defs: {}, names: {} }, extra: { defs: {}, names: {} } };
const bad = [];
for (const [k, d] of Object.entries(raw.defs)) {
  try {
    proj4.defs(k, d);
    // Round-trip the centre of the CRS's area of use: forward then inverse
    // must be finite and return within 1e-6 deg.
    const c = (raw.centres && raw.centres[k]) || [-95, 40];
    const xy = proj4("WGS84", k, c);
    const ll = proj4(k, "WGS84", xy);
    if (![...xy, ...ll].every(Number.isFinite)) throw new Error("non-finite");
    if (Math.abs(ll[0] - c[0]) > 1e-6 || Math.abs(ll[1] - c[1]) > 1e-6) throw new Error("round-trip mismatch");
    out[raw.tiers[k] === "core" ? "core" : "extra"].defs[k] = d;
  } catch (e) { bad.push(`${k} ${e.message}`); }
}
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "");
for (const [n, k] of Object.entries(raw.names)) {
  for (const t of ["core", "extra"]) if (out[t].defs[k]) out[t].names[norm(n)] = k;
}
const head = "// AUTO-GENERATED by tools/gen_crs_us.py + tools/validate_crs_us.js. Do not edit.\n";
fs.writeFileSync(path.join(root, "crs-us.js"), head +
  "// Core US coordinate systems (State Plane NAD27/NAD83 all realisations + units,\n" +
  "// UTM, statewide and national systems). Shipped and precached for offline use.\n" +
  "window.CRS_US_DEFS=" + JSON.stringify(out.core.defs) + ";\n" +
  "window.CRS_US_NAMES=" + JSON.stringify(out.core.names) + ";\n");
fs.writeFileSync(path.join(root, "crs-us-extra.js"), head +
  "// County, city, regional and world coordinate systems. Downloaded by\n" +
  "// IFCViewer.loadExtraCrs() the first time a model needs one; then kept offline.\n" +
  "window.CRS_US_EXTRA_DEFS=" + JSON.stringify(out.extra.defs) + ";\n" +
  "window.CRS_US_EXTRA_NAMES=" + JSON.stringify(out.extra.names) + ";\n");
process.stderr.write(`core ${Object.keys(out.core.defs).length}, extra ${Object.keys(out.extra.defs).length}, dropped ${bad.length}\n`);
